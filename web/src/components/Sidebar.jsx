/**
 * Sidebar navigation component.
 */
export default function Sidebar({ activePage, onNavigate, alertCount = 0 }) {
  const navItems = [
    { section: 'Monitor' },
    { id: 'overview', label: 'Overview', icon: <LayoutIcon /> },
    { id: 'resources', label: 'Resource Monitor', icon: <ActivityIcon /> },
    { id: 'processes', label: 'Process Explorer', icon: <ListIcon /> },
    { section: 'Analysis' },
    { id: 'insights', label: 'Health Insights', icon: <BrainIcon />, badge: alertCount > 0 ? alertCount : null },
    { id: 'recommendations', label: 'Recommendations', icon: <LightbulbIcon /> },
    { id: 'history', label: 'History', icon: <ClockIcon /> },
    { section: 'System' },
    { id: 'settings', label: 'Settings', icon: <SettingsIcon /> },
    { id: 'about', label: 'About', icon: <InfoIcon /> },
  ];

  return (
    <aside className="sidebar">
      <div className="sidebar-header">
        <div className="sidebar-brand">
          <div className="sidebar-brand-icon">
            <MonitorIcon />
          </div>
          <div className="sidebar-brand-text">
            <h1>Health Monitor</h1>
            <span>OS Diagnostics</span>
          </div>
        </div>
      </div>

      <nav className="sidebar-nav">
        {navItems.map((item, i) => {
          if (item.section) {
            return (
              <div key={`section-${i}`} className="nav-section-label">
                {item.section}
              </div>
            );
          }
          return (
            <div
              key={item.id}
              className={`nav-item ${activePage === item.id ? 'active' : ''}`}
              onClick={() => onNavigate(item.id)}
              role="button"
              tabIndex={0}
              onKeyDown={(e) => e.key === 'Enter' && onNavigate(item.id)}
            >
              {item.icon}
              <span>{item.label}</span>
              {item.badge != null && <span className="nav-badge">{item.badge}</span>}
            </div>
          );
        })}
      </nav>

      <div className="sidebar-footer">
        <div className="sidebar-status">
          <span className="status-dot" />
          <span>Simulation Active</span>
        </div>
      </div>
    </aside>
  );
}

